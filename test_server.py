def test_second_job_conflict(client):
    # Start an import that will block on the preview prompt, then a second start -> 409.
    # Use a source with one file so it reaches the preview and waits.
    import tempfile
    src = tempfile.mkdtemp()
    _make_mp3(__import__("pathlib").Path(src) / "s.mp3",
              TIT2="A", TPE1="B", TPE2="B", TALB="C", TYER="2020", TRCK="1")
    first = client.post("/api/jobs", json={"kind": "import", "source": src}).json()["job_id"]
    # wait until it is waiting on preview
    for _ in range(200):
        if client.get(f"/api/jobs/{first}").json()["state"] == "waiting":
            break
        time.sleep(0.02)
    resp = client.post("/api/jobs", json={"kind": "standardize", "dry_run": True})
    assert resp.status_code == 409
    client.post(f"/api/jobs/{first}/cancel")  # release
    shutil.rmtree(src, ignore_errors=True)



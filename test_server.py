def test_standardize_prompt_roundtrip(tmp_path):
    if shutil.which("ffmpeg") is None:
        pytest.skip("ffmpeg not available")
    # A file missing TIT2 forces step 2 (fix missing tags) to prompt.
    album = tmp_path / "Artist" / "2024 - Album"
    _make_mp3(album / "01. Artist - Track.mp3",
              TPE1="Artist", TPE2="Artist", TALB="Album", TYER="2024", TRCK="01/1")
    server.set_root(tmp_path)
    c = TestClient(server.app)

    asked = []

    def answer(prompt):
        asked.append(prompt["kind"])
        if prompt["kind"] == "text" and "Title" in prompt["prompt"]:
            return "Filled In"
        if prompt["kind"] == "choice" and prompt["options"]:
            return prompt["options"][0]["key"]
        return ""

    jid = c.post("/api/jobs", json={"kind": "standardize", "dry_run": False}).json()["job_id"]
    j = _poll(c, jid, answer)
    assert j["state"] == "done", j.get("error")
    assert "text" in asked, "expected at least one text prompt"
    # The title we supplied should now be on disk (file likely renamed to match).
    written = list((tmp_path / "Artist").rglob("*.mp3"))
    assert written
    tags = ID3(written[0], translate=False)
    assert str(tags.get("TIT2")) == "Filled In"


